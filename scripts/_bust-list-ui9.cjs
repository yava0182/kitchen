const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const htmlPath = path.join(root, 'admin-new.html');
let h = fs.readFileSync(htmlPath, 'utf8');
h = h.replace(/html v=20261022-list-ui\d+/g, 'html v=20261022-list-ui9');
h = h.replace(/html loaded v=20261022-list-ui\d+/g, 'html loaded v=20261022-list-ui9');
h = h.replace(/\?v=20261022-list-ui\d+/g, '?v=20261022-list-ui9');
fs.writeFileSync(htmlPath, h);
fs.copyFileSync(htmlPath, path.join(root, 'public', 'admin-new.html'));
fs.copyFileSync(path.join(root, 'js', 'admin', 'admin-new-bundle.js'), path.join(root, 'public', 'js', 'admin', 'admin-new-bundle.js'));
fs.copyFileSync(path.join(root, 'admin-handles-list.js'), path.join(root, 'public', 'admin-handles-list.js'));
console.log('ok', (h.match(/html v=20261022-list-ui\d+/) || [])[0]);
